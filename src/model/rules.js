export const ALL_RULES = [...NEGATIVE_RULES, ...POSITIVE_RULES];
const NEGATIVE_IDS = new Set(NEGATIVE_RULES.map((r) => r.id));

/** 규칙 매칭 대상 글자 수 상한 (아주 긴 제목이 정규식을 오래 붙잡지 않게 — 제목은 보통 100자 안쪽) */
const TEXT_MAX = 400;

/**
 * 규칙 판정. funny·vibe 는 로지스틱 점수(logit)에 더할 값 (neg·pos 는 감점·가점 묶음 따로), caps 는 최종 점수 상한, hits 는 걸린 묶음 id.
 * @param {string} text features.js ruleText(post) 결과
 * @returns {{funny: number, vibe: number, neg: {funny: number, vibe: number}, pos: {funny: number, vibe: number},
 *   caps: {funny: number, vibe: number}, hits: string[]}}
 */
export function applyRules(text) {
  const t = String(text ?? '').slice(0, TEXT_MAX);
  const neg = { funny: 0, vibe: 0 };
  const pos = { funny: 0, vibe: 0 };
  const caps = { funny: 100, vibe: 100 };
  const hits = [];
  for (const r of ALL_RULES) {
    if (!r.re.some((re) => re.test(t))) continue;
    hits.push(r.id);
    const side = NEGATIVE_IDS.has(r.id) ? neg : pos;
    side.funny += r.funny;
    side.vibe += r.vibe;
    if (r.cap?.funny != null) caps.funny = Math.min(caps.funny, r.cap.funny);
    if (r.cap?.vibe != null) caps.vibe = Math.min(caps.vibe, r.cap.vibe);
  }
  return { funny: neg.funny + pos.funny, vibe: neg.vibe + pos.vibe, neg, pos, caps, hits };
}

/**
 * 규칙 가감을 학습 점수(logit)에 더할 값으로: scale 이 수면 전체에 곱하고, {neg, pos} 면 감점·가점 묶음에 따로 곱한다.
 * @param {ReturnType<typeof applyRules>} rules
 * @param {'funny'|'vibe'} target
 * @param {number|{neg?: number, pos?: number}} [scale]
 */
export function ruleDelta(rules, target, scale = 1) {
  if (typeof scale === 'number') return scale * rules[target];
  return (scale?.neg ?? 1) * rules.neg[target] + (scale?.pos ?? 1) * rules.pos[target];
}
